import java.time.LocalDateTime
import java.time.format.DateTimeFormatter
import java.util.Properties

plugins {
    java
}

group = "io.github.youqing"
version = "0.0.1"

// 构建输出默认放在工作区之外：本机有外部索引进程会锁住工作区里的测试报告文件，
// 导致 Gradle 无法覆盖旧报告而构建失败（详见 docs/dev-notes.md）。
// 可用 local.properties 的 build.dir 覆盖。
val localProps = Properties().apply {
    val f = file("local.properties")
    if (f.exists()) {
        f.inputStream().use { load(it) }
    }
}
val externalBuildDir = localProps.getProperty("build.dir")
    ?: (System.getProperty("user.home") + "/.sts1-combatsolver/build")
layout.buildDirectory.set(file(externalBuildDir))

repositories {
    mavenCentral()
}

// 每次构建生成一个时间戳常量，运行时会打进日志和面板。
// 目的：判断「游戏里跑的是不是最新包」不该靠比对文件时间，版本要能自证。
val stampDir = layout.buildDirectory.dir("generated/buildstamp")
val generateBuildStamp = tasks.register("generateBuildStamp") {
    outputs.dir(stampDir)
    // 每次构建都重新生成：否则 Gradle 判定 up-to-date，两个不同的包会共用同一个时间戳
    outputs.upToDateWhen { false }
    doLast {
        val file = stampDir.get().file("io/github/youqing/sts1solver/BuildStamp.java").asFile
        file.parentFile.mkdirs()
        val now = LocalDateTime.now().format(DateTimeFormatter.ofPattern("MMdd-HHmmss"))
        file.writeText(
            "package io.github.youqing.sts1solver;\n\n" +
                "/** Generated by Gradle - do not edit. */\n" +
                "public final class BuildStamp {\n" +
                "    public static final String VALUE = \"" + now + "\";\n" +
                "}\n"
        )
    }
}
sourceSets.main {
    java.srcDir(generateBuildStamp)
}

// 第三方编译依赖：从游戏目录同步到 lib/（见 tools/sync-libs.ps1），不入库
dependencies {
    implementation(fileTree("lib") { include("*.jar") })

    testImplementation(platform("org.junit:junit-bom:5.11.4"))
    testImplementation("org.junit.jupiter:junit-jupiter")
    testRuntimeOnly("org.junit.platform:junit-platform-launcher")
}

// 游戏运行在 JRE 8 上，产物必须是 class 版本 52
tasks.withType<JavaCompile>().configureEach {
    options.release.set(8)
    options.encoding = "UTF-8"
    options.compilerArgs.add("-Xlint:-options")
}

tasks.test {
    useJUnitPlatform()
    // HTML 报告在本机会被外部索引进程占用句柄，导致 Gradle 无法清理旧报告而构建失败。
    // 只保留 JUnit XML（CI 与脚本都用它），需要人读时再临时打开 HTML。
    reports.html.required.set(false)
    reports.junitXml.required.set(true)
    // 回合重放探针（TurnReplayProbeTest）：gradlew test -Dreplay=<snapshot.json>
    // Gradle 不会把命令行 -D 自动转给测试 JVM，这里显式转发一次。
    providers.systemProperty("replay").orNull?.let { systemProperty("replay", it) }
    // 离线实验（@Disabled 的那些）靠这个开关打开：gradle test -Pexperiments
    // 这样不用改源码就能跑 A/B，也就不会出现「忘了把 @Disabled 加回去」。
    if (project.hasProperty("experiments")) {
        filter {
            includeTestsMatching("*ScoreAbTest*")
            includeTestsMatching("*SelfPlayTest*")
        }
        systemProperty("sts1.experiments", "true")
    }
}

tasks.jar {
    archiveFileName.set("STS1CombatSolver.jar")
    manifest {
        attributes(
            "Implementation-Title" to "STS1 Combat Solver",
            "Implementation-Version" to project.version.toString()
        )
    }
}
